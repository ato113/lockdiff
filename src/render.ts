import { hasBreaking } from "./diff";
import type { Change, Digest, FileDigest, Updated } from "./types";

export const MARKER = "<!-- lockdiff -->";

const ECOSYSTEM_LABEL = { npm: "npm", yarn: "Yarn", pip: "pip" } as const;

function plural(count: number, word: string): string {
  return `${count} ${word}${count === 1 ? "" : "s"}`;
}

function headline(changes: Change[]): string {
  const added = changes.filter((c) => c.kind === "added").length;
  const removed = changes.filter((c) => c.kind === "removed").length;
  const updated = changes.filter((c) => c.kind === "updated").length;

  const pieces: string[] = [];
  if (added) pieces.push(`${added} added`);
  if (updated) pieces.push(`${updated} updated`);
  if (removed) pieces.push(`${removed} removed`);
  return pieces.length > 0 ? pieces.join(", ") : "no changes";
}

function describe(change: Updated): string {
  if (change.downgrade) return `${change.from} → ${change.to} — **downgrade**`;
  if (change.bump === "major") return `${change.from} → ${change.to} — **major**`;
  return `${change.from} → ${change.to}`;
}

function renderFile(file: FileDigest): string {
  const label = ECOSYSTEM_LABEL[file.ecosystem];
  const lines = [`### \`${file.path}\``, "", `${label} · ${headline(file.changes)}`, ""];

  const attention = file.changes.filter(
    (c): c is Updated => c.kind === "updated" && (c.downgrade || c.bump === "major"),
  );

  if (attention.length > 0) {
    lines.push("**Worth a look**", "");
    for (const change of attention) {
      lines.push(`- \`${change.name}\` ${describe(change)}`);
    }
    lines.push("");
  }

  const rest = file.changes.filter((c) => !attention.includes(c as Updated));
  if (rest.length > 0) {
    lines.push("<details>", `<summary>${plural(rest.length, "other change")}</summary>`, "");
    for (const change of rest) {
      const dev = change.dev ? " _(dev)_" : "";
      if (change.kind === "added") {
        lines.push(`- \`${change.name}\` added at ${change.version}${dev}`);
      } else if (change.kind === "removed") {
        lines.push(`- \`${change.name}\` removed (was ${change.version})${dev}`);
      } else {
        lines.push(`- \`${change.name}\` ${describe(change)}${dev}`);
      }
    }
    lines.push("", "</details>", "");
  }

  return lines.join("\n");
}

/** Render the whole digest as the body of a pull request comment. */
export function render(digest: Digest): string {
  const changed = digest.files.filter((file) => file.changes.length > 0);

  if (changed.length === 0) {
    return [MARKER, "## Lockfile changes", "", "No dependency changes in this pull request."].join(
      "\n",
    );
  }

  const total = changed.reduce((sum, file) => sum + file.changes.length, 0);
  const breaking = changed.some((file) => hasBreaking(file.changes));

  const lines = [
    MARKER,
    "## Lockfile changes",
    "",
    breaking
      ? `${plural(total, "change")} across ${plural(changed.length, "file")}, including major version bumps.`
      : `${plural(total, "change")} across ${plural(changed.length, "file")}.`,
    "",
  ];

  for (const file of changed) {
    lines.push(renderFile(file));
  }

  lines.push("", "<sub>Generated by [lockdiff](https://github.com/ato113/lockdiff).</sub>");
  return lines.join("\n");
}

/** A one-line version for the Actions run summary and the step output. */
export function summarize(digest: Digest): string {
  const total = digest.files.reduce((sum, file) => sum + file.changes.length, 0);
  if (total === 0) return "No dependency changes.";
  const breaking = digest.files.some((file) => hasBreaking(file.changes));
  return breaking
    ? `${plural(total, "dependency change")}, including major bumps.`
    : `${plural(total, "dependency change")}.`;
}
